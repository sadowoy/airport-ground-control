CREATE TABLE modelo_aeronave (
  modelo_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  fabricante VARCHAR(50) NOT NULL,
  nome VARCHAR(50) NOT NULL,
  mtow_kg NUMERIC(10,2) NOT NULL,
  CONSTRAINT pk_modelo PRIMARY KEY (modelo_id),
  CONSTRAINT ck_modelo_mtow CHECK (mtow_kg > 0)
);

CREATE TABLE aeronave (
  aeronave_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  modelo_id INTEGER NOT NULL,
  prefixo VARCHAR(10) NOT NULL,
  ano_fabricacao INTEGER NOT NULL,
  CONSTRAINT pk_aeronave PRIMARY KEY (aeronave_id),
  CONSTRAINT uk_aeronave_prefixo UNIQUE (prefixo),
  CONSTRAINT fk_aeronave_modelo FOREIGN KEY (modelo_id) REFERENCES modelo_aeronave (modelo_id) ON DELETE RESTRICT,
  CONSTRAINT ck_aero_ano CHECK (ano_fabricacao > 1900)
);

CREATE TABLE pista (
  pista_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  numero_identificacao VARCHAR(10) NOT NULL,
  tamanho_metros INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  CONSTRAINT pk_pista PRIMARY KEY (pista_id),
  CONSTRAINT uk_pista_numero UNIQUE (numero_identificacao),
  CONSTRAINT ck_pista_tamanho CHECK (tamanho_metros > 0)
);

CREATE TABLE voo (
  voo_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  aeronave_id INTEGER NOT NULL,
  pista_id INTEGER NOT NULL,
  data_hora_prevista TIMESTAMP NOT NULL,
  peso_total_kg NUMERIC(10,2) NOT NULL,
  status VARCHAR(20) NOT NULL,
  CONSTRAINT pk_voo PRIMARY KEY (voo_id),
  CONSTRAINT fk_voo_aeronave FOREIGN KEY (aeronave_id) REFERENCES aeronave (aeronave_id) ON DELETE RESTRICT,
  CONSTRAINT fk_voo_pista FOREIGN KEY (pista_id) REFERENCES pista (pista_id) ON DELETE RESTRICT,
  CONSTRAINT ck_voo_peso CHECK (peso_total_kg > 0)
);

CREATE TABLE tripulante (
  tripulante_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  matricula VARCHAR(20) NOT NULL,
  nome VARCHAR(100) NOT NULL,
  cargo VARCHAR(50) NOT NULL,
  CONSTRAINT pk_tripulante PRIMARY KEY (tripulante_id),
  CONSTRAINT uk_tripulante_matricula UNIQUE (matricula)
);

CREATE TABLE escala_voo (
  voo_id INTEGER NOT NULL,
  tripulante_id INTEGER NOT NULL,
  funcao_exercida VARCHAR(50) NOT NULL,
  horas_computadas NUMERIC(5,2),
  CONSTRAINT pk_escala PRIMARY KEY (voo_id, tripulante_id),
  CONSTRAINT fk_escala_voo FOREIGN KEY (voo_id) REFERENCES voo (voo_id) ON DELETE RESTRICT,
  CONSTRAINT fk_escala_tripulante FOREIGN KEY (tripulante_id) REFERENCES tripulante (tripulante_id) ON DELETE RESTRICT,
  CONSTRAINT ck_escala_horas CHECK (horas_computadas >= 0)
);

CREATE TABLE ordem_manutencao (
  ordem_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
  aeronave_id INTEGER NOT NULL,
  nivel_severidade INTEGER NOT NULL,
  status VARCHAR(20) NOT NULL,
  data_abertura DATE NOT NULL,
  CONSTRAINT pk_ordem PRIMARY KEY (ordem_id),
  CONSTRAINT fk_ordem_aeronave FOREIGN KEY (aeronave_id) REFERENCES aeronave (aeronave_id) ON DELETE RESTRICT,
  CONSTRAINT ck_ordem_severidade CHECK (nivel_severidade BETWEEN 1 AND 5)
);